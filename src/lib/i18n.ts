const dict: Record<Lang, Record<TKey, string>> = { en, th };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useVessa((s) => s.lang);
  return useCallback(
    (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );
}

export function localeOf(lang: Lang) {
  return lang === "th" ? "th-TH-u-ca-gregory" : "en-GB";
}

export function useLocale() {
  return localeOf(useVessa((s) => s.lang));
}

export function monthNames(lang: Lang, style: "long" | "short" = "long") {
  const fmt = new Intl.DateTimeFormat(localeOf(lang), { month: style });
  return Array.from({ length: 12 }, (_, i) => fmt.format(new Date(2020, i, 1)));
}
